/**
 * 지도가 멎었을 때(`onIdle`) **무엇을 할 것인가** — 자동 재검색 / 버튼 띄우기 / 아무것도 안 함.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * ■ 왜 규칙이 갈리는가 (국내 지도 앱들이 실제로 하는 것)
 *
 * 종전 규칙은 하나였다: **어떤 움직임이든 자동 재조회를 하지 않는다.** 팬이든 줌이든
 * `현재 지도에서 찾기` 를 눌러야 결과가 바뀌었다. 그런데 그 규칙은 사용자가 지도를
 * 다루는 두 가지 서로 다른 동작을 한 덩어리로 묶는다:
 *
 *  - **팬(이동)** 은 "여기 말고 저기" 다. 자동으로 재검색하면 손가락으로 미는 동안 목록이
 *    계속 갈리고 스크롤이 튄다. 그래서 네이버 지도 · 카카오맵 · 구글 지도가 **전부**
 *    `이 지역 검색` 버튼을 띄운다. 이건 유지한다.
 *  - **줌(확대·축소)** 은 "같은 자리를 더 좁게/넓게" 다. 사용자는 방금 본 결과의 **범위**를
 *    바꾼 것이고, 그 결과가 그대로 남아 있으면 화면이 고장 난 것으로 읽힌다(확대했는데
 *    화면 밖 가게가 목록에 그대로 남아 있다). 지도 앱들은 이때 결과를 바로 갱신한다.
 *
 * 그래서 **줌이 바뀌면 자동으로 다시 찾고, 위치만 바뀌면 버튼을 띄운다.**
 *
 * ■ 왜 순수 함수인가
 *
 * 이 판단이 훅 안의 `if` 로 있으면 검증할 방법이 없다(이 저장소의 jest 는 RN 을 렌더하지
 * 못한다). 그리고 이건 조용히 틀리는 종류의 규칙이다 — 팬에서 자동 재검색이 켜지면
 * 요청이 폭주하고, 줌에서 꺼지면 사용자는 "지도가 안 따라온다" 고 느낀다.
 *
 * ■ 면적 상한은 여기서 보지 않는다
 *
 * bbox 가 서버 상한을 넘는지는 `isBboxTooLarge` 가 판단하고, 그 처리는 호출부(훅)의 일이다.
 * 이 함수는 **의도**만 읽는다(움직임의 종류). 두 판단을 섞으면 "너무 넓어서 안 찾음" 과
 * "팬이라 안 찾음" 이 같은 반환값이 되어 화면이 서로 다른 안내를 고를 수 없다.
 */

export interface ViewportSnapshot {
  /** 정규화·라운딩이 끝난 bbox 키. 같은 상자면 같은 문자열이어야 한다. */
  bboxKey: string
  /** 정수로 조인 줌 레벨. */
  zoom: number
}

export type ViewportAction =
  /** 줌이 바뀌었다 → 바로 다시 찾는다(버튼을 띄우지 않는다). */
  | "search"
  /** 위치만 바뀌었다 → `이 지역 검색` 버튼을 띄운다. */
  | "prompt"
  /** 확정된 것과 같은 화면이다 → 아무것도 하지 않는다. */
  | "idle"

/**
 * @param committed 마지막으로 **확정된**(질의가 나간) 뷰포트. 첫 진입에는 `null`.
 * @param next      지금 지도가 보고 있는 뷰포트.
 */
export function resolveViewportAction(
  committed: ViewportSnapshot | null,
  next: ViewportSnapshot,
): ViewportAction {
  /*
    첫 뷰포트. 확정된 것이 없으므로 **찾는다** — 지도를 열었는데 빈 목록을 보여 주고
    버튼을 누르게 하는 앱은 없다. (호출부가 이미 첫 검색을 하고 있더라도 같은 키라
    react-query 가 한 번만 나간다.)
  */
  if (committed === null) return "search"

  if (committed.zoom !== next.zoom) return "search"
  if (committed.bboxKey !== next.bboxKey) return "prompt"
  return "idle"
}

