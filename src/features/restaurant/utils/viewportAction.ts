/**
 * 클러스터를 눌렀을 때 갈 **줌 레벨**.
 *
 * ## 왜 레벨 계산인가 (fitBounds 를 버린 이유)
 *
 * 종전에는 현재 뷰포트를 1/4 로 줄인 상자를 만들어 `fitBounds` 로 맞췄다. 그런데 그 상자는
 * **전체 뷰포트**에서 뽑고, 맞추는 곳은 시트·상단 오버레이를 뺀 **보이는 영역**이었다.
 * 두 축소가 서로 상쇄된다:
 *
 *   화면 874 · 상단 오버레이 ~166 · 시트(mid) ~480  →  보이는 높이 ~212 (24%)
 *   상자 높이 = 뷰포트의 25%
 *   → 25% 짜리 상자를 24% 짜리 창에 맞춘다 = 배율 ≈ 1.0 (확대가 없다)
 *
 * 반올림이 어느 쪽으로 떨어지느냐에 따라 **한 단계 축소**되기도 한다. 그래서 누를수록
 * 조금씩 축소되다가, 축소 한계에 닿으면 그때부터 한 단계씩 확대되는 것처럼 보였다
 * (사용자 보고). 시트가 expanded 면 패딩이 화면보다 커져 계산이 아예 무너진다.
 *
 * 카카오 레벨은 한 단계가 2배다. 그러니 "4배 확대" 는 **레벨 −2** 로 정확히 표현된다.
 * 위치는 `focusMarker`(보이는 영역의 중앙에 놓는 명령)가 잡으므로 패딩 산수가 사라진다 —
 * 확대량과 위치를 **각각 맞는 도구로** 나눈 것이 이 함수의 요지다.
 */
export const CLUSTER_ZOOM_STEP = 2

export function nextClusterZoom(
  current: number,
  min: number,
  step: number = CLUSTER_ZOOM_STEP,
): number {
  if (!Number.isFinite(current)) return min
  // 레벨이 작을수록 확대다. 하한 아래로 내려가지 않는다.
  return Math.max(min, Math.round(current) - step)
}
