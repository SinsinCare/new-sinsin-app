/**
 * 식당 기능의 **레이아웃 격자**. 이 파일이 정본이고, 화면·컴포넌트는 여기서만 값을 가져온다.
 *
 * ## 왜 만들었나
 *
 * 상세 화면에서 "컴포넌트들이 따로 노는 느낌" 이라는 지적을 받았다. 실제로 그랬다 —
 * 좌우 여백만 세어 봐도 `16`(36곳) · `24`(10곳) · `12`(7곳) · `10` · `8` · `6` · `2` 가
 * 섞여 있었다. 값 하나하나는 그럴듯해 보이지만, 화면에서는 **왼쪽 시작선이 여러 개**로
 * 보이고 그게 "따로 노는" 느낌의 정체다.
 *
 * 문제는 값이 틀린 것이 아니라 **기준이 없어서 매번 다시 정했다는 것**이다. 그래서
 * 숫자를 고치는 대신 기준을 만든다.
 *
 * ## 두 층으로 나눈다 (섞으면 안 된다)
 *
 * - **화면(screen)**: 좌우 `16`. 목업이 그렇다(DESIGN_SPEC §10 "화면 좌우 16").
 *   지도 홈·리스트·상세가 전부 이 값이다.
 * - **모달 시트(sheet)**: 좌우 `24`. design-system-v2 의 `V2BottomSheet` 가 제목·본문·푸터를
 *   `spacing[24]` 로 잡는다. 필터/정렬/AI 검색 시트는 이미 전부 24 라 **일관돼 있었다** —
 *   여기는 고칠 것이 없다. 시트를 16 으로 끌어내리면 오히려 DS 와 어긋난다.
 *
 * 두 값이 다른 것은 실수가 아니라 표면이 다르기 때문이다. 다만 **한 표면 안에서는 하나**여야 한다.
 *
 * ## 아이콘 행의 시작선
 *
 * 상세의 정보 행(영업시간·주소·전화·링크)은 아이콘 뒤에 텍스트가 온다. 이때 텍스트가
 * 각 행마다 다른 x 에서 시작하면 문단이 흔들려 보인다. 아이콘은 화면 여백에서 시작하고
 * 텍스트는 항상 `GUTTER + ICON + GAP` 에서 시작한다 — 그 값이 `TEXT_INDENT` 다.
 * 섹션 제목처럼 아이콘이 없는 줄은 `GUTTER` 에서 시작하므로, 두 시작선이 의도적으로
 * 두 개다(제목 < 본문). 세 번째가 생기면 그때가 무너지는 순간이다.
 */

import { iconSize, radius, spacing } from "@/src/design-system-v2"

/** 화면 좌우 여백. 목업 §10. 지도·리스트·상세가 공유한다. */
export const GUTTER = spacing[16]

/**
 * 모달 시트 좌우 여백. `V2BottomSheet` 와 같은 값이라 시트 안의 DS 컴포넌트와 선이 맞는다.
 * 화면(`GUTTER`)과 다른 것은 의도다 — 위 머리말 참고.
 */
export const SHEET_GUTTER = spacing[24]

/** 정보 행의 아이콘 크기. `V2Icon size="sm"` 과 같은 값이어야 선이 맞는다. */
export const ROW_ICON = iconSize.sm

/** 아이콘과 텍스트 사이. 목업 §10 "아이콘-텍스트 gap 8". */
export const ROW_ICON_GAP = spacing[8]

/**
 * 아이콘이 있는 행에서 **텍스트가 시작하는 x**(화면 왼쪽 기준).
 * 아이콘 없는 줄을 이 값에 맞추고 싶을 때도 쓴다 — 예: 아이콘 행 아래에 붙는 보조 설명.
 */
export const TEXT_INDENT = GUTTER + ROW_ICON + ROW_ICON_GAP

/** 섹션 사이 세로 여백. 목업 §10 "섹션 상하 20~24" 의 하한을 기본으로 쓴다. */
export const SECTION_GAP = spacing[20]

/** 섹션 제목과 그 내용 사이. */
export const SECTION_TITLE_GAP = spacing[12]

/** 목록 항목 사이. 카드 리스트는 divider + 이 값이다(목업 §2.8). */
export const ITEM_GAP = spacing[16]

/** 칩끼리의 간격. 목업 §10 "칩 gap 8". */
export const CHIP_GAP = spacing[8]

/**
 * 섹션을 끊는 두꺼운 회색 띠의 높이. `V2Divider variant="thick"` 이 16 을 쓰므로 같은 값이다.
 * 상세의 큰 덩어리(정보 / 메뉴 / 사진 / 후기) 사이에만 쓴다 — 매 섹션에 넣으면 화면이 줄무늬가 된다.
 */
export const SECTION_BAND = spacing[16]

/**
 * 정보 덩어리를 묶는 **둥근 회색 카드**의 안쪽 여백.
 *
 * 상세의 정보 블록(영업시간·주소·전화·링크 / 편의시설 / 주차 / SNS)은 오랫동안
 * 머리카락 선으로만 나뉘어 있었다. 선은 "여기가 끝" 을 말하지만 "이 다섯 줄이 한
 * 덩어리" 를 말하지는 못해서, 화면이 균일한 회색 줄무늬로 보이고 어디부터 어디까지가
 * 한 주제인지 읽히지 않았다(사용자 지적: "덩어리가 안 보인다").
 *
 * 면으로 묶으면 그 경계가 한눈에 잡힌다. 다만 면을 쓰는 순간 안쪽 여백이 좁으면
 * 글자가 상자에 갇혀 보이므로 `GUTTER` 와 같은 값을 안쪽에도 준다 — 화면 여백과
 * 카드 여백이 같은 수라 카드 안팎의 리듬이 어긋나지 않는다.
 */
export const CARD_PADDING = GUTTER

/**
 * 그 카드의 모서리. `radius.lg`(12) 와 같은 값이며, 히어로 캐러셀 사진의 모서리와도
 * 같다 — 한 화면에 곡률이 두 개면 카드가 사진과 다른 재질처럼 보인다.
 */
export const CARD_RADIUS = radius.lg

/**
 * 카드끼리의 간격. 카드가 면으로 이미 끊고 있으므로 섹션 간격보다 좁게 둔다 —
 * `SECTION_GAP` 을 그대로 쓰면 카드 사이가 화면 여백처럼 벌어져 목록이 흩어진다.
 */
export const CARD_GAP = spacing[12]

/**
 * 가로 스크롤(사진 스트립·칩 레일)의 **첫 항목 왼쪽 인셋**.
 *
 * 가로 스크롤은 컨테이너에 `paddingHorizontal` 을 주면 안 된다 — 오른쪽 패딩이 스크롤
 * 끝에서 잘려 마지막 항목이 화면에 붙는다. `contentContainerStyle` 에 이 값을 주고
 * 컨테이너 자체는 화면 끝까지 두어야 목업처럼 다음 항목이 살짝 보인다.
 */
export const RAIL_INSET = GUTTER
