/**
 * 화면에 숫자를 내보내기 직전의 반올림.
 *
 * ## 왜 필요한가
 *
 * 서버가 주는 수분·체중·영양소는 전부 double 이고, 화면은 그것들을 **빼거나 더해서**
 * 보여준다. IEEE 754 에서 `1500 - 1860.9` 는 `-360.90000000000009` 다. 그대로
 * 문자열에 넣으면 사용자는 `기준보다 360.9000000000001ml 많아요` 를 읽는다
 * (2026-08-04 QA 정설아). 계산이 틀린 게 아니라 **표시가 원시값을 그대로 흘린 것**이다.
 *
 * ## 규칙
 *
 * 저장·계산은 원시값 그대로 두고, **화면에 나가는 마지막 한 걸음에서만** 접는다.
 * 반올림한 값을 다시 계산에 넣으면 오차가 쌓인다.
 *
 * 단위별 자릿수는 도메인이 정한다 — mL·mg 는 정수(소수점이 의미 없다), kg 은 한 자리
 * (체중계의 눈금), g 은 한 자리. 그 선택은 호출부에 남긴다.
 */

/**
 * 표시용 반올림. `Math.round(v * 10 ** d) / 10 ** d` 를 한 곳에 모은 것이다 —
 * 이 식이 화면 코드 여기저기에 흩어져 있으면 어떤 자리는 접고 어떤 자리는 안 접는
 * 지금 같은 상태가 된다.
 *
 * 유한하지 않은 값(NaN·Infinity)은 그대로 돌려준다. 여기서 0 으로 바꾸면 "값이 없다"와
 * "계산이 깨졌다"가 화면에서 같아 보인다 — 그 판단은 호출부의 몫이다.
 */
export function roundForDisplay(value: number, decimals = 0): number {
  if (!Number.isFinite(value)) return value
  const factor = 10 ** decimals
  // `+0` 을 곱해 `-0` 을 지운다. `-0` 은 문자열로 "0" 이지만 `Object.is` 비교와
  // 부호 분기(`value < 0`)에서 사람이 예상하지 못한 쪽으로 샌다.
  return Math.round(value * factor) / factor + 0
}
